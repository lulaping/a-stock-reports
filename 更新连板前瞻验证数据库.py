RED = Font(color="CC0000", bold=True)
GREEN = Font(color="008000", bold=True)
THIN = Side(style="thin", color="444444")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)

def sheet_headers(ws, headers, widths):
    ws.append(headers)
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
        c = ws.cell(row=1, column=i)
        c.fill = HDR_FILL; c.font = HDR_FONT; c.alignment = Alignment(horizontal="center", vertical="center"); c.border = BORDER
    ws.freeze_panes = "A2"

def style_rows(ws, last_col, rows):
    for r in range(2, rows + 2):
        for col in range(1, last_col + 1):
            c = ws.cell(row=r, column=col); c.border = BORDER; c.font = Font(size=10)
            v = str(c.value or "")
            if "跌停" in v or v.startswith("-") or "✗" in v or "断板" in v: c.font = RED
            elif "涨停" in v or "晋级" in v or "✓" in v: c.font = GREEN
        ws.row_dimensions[r].height = 20

